def _varlen(value):
    out = [value & 0x7F]
    value >>= 7
    while value:
        out.insert(0, (value & 0x7F) | 0x80)
        value >>= 7
    return bytes(out)


def _chunk(kind, body):
    return kind + len(body).to_bytes(4, "big") + body


def selftest():
    q = 480
    # Track 0: 3/4, then end of track.
    conductor = (_varlen(0) + bytes([0xFF, 0x58, 4, 3, 2, 24, 8]) +
                 _varlen(0) + bytes([0xFF, 0x51, 3, 0x07, 0xA1, 0x20]) +  # a tempo, ignored
                 _varlen(3 * q) + bytes([0xFF, 0x2F, 0]))
    # Track 1: notes with running status, a velocity-0 note-off, an eighth off
    # the beat, and drums on channel 10 (one not in DRUMS).
    events = [
        (0, [0x90, 60, 100]),        # C4 on
        (0, [36, 100]),              # running status: C2 on, same channel... (pitched)
        (0, [0x99, 36, 100]),        # drum: kick
        (q, [0x89, 36, 0]),          # kick off
        (0, [0x99, 38, 90]),         # snare
        (0, [42, 80]),               # running status: hi-hat, not in DRUMS
        (0, [0x90, 60, 0]),          # C4 off (velocity 0)
        (0, [36, 0]),                # C2 off
        (q // 2, [0x90, 64, 100]),   # E4 at beat 1.5, an eighth
        (q // 2, [64, 0]),
        (0, [0x99, 38, 0]),
        (0, [42, 0]),
        (0, [0x90, 70, 100]),        # Bb4 at beat 2
        (q, [0x80, 70, 0]),
        (0, [0xFF, 0x2F, 0]),
    ]
    notes_track = b"".join(_varlen(delta) + bytes(body) for delta, body in events)
    midi = (_chunk(b"MThd", (1).to_bytes(2, "big") + (2).to_bytes(2, "big") + q.to_bytes(2, "big")) +
            _chunk(b"MTrk", conductor) + _chunk(b"MTrk", notes_track))

    lines, report = to_score(*read_midi(midi))
    expected = ["Kick C2 C4", "Snare E4", "Bb4"]
    failures = 0

    def check(ok, what):
        nonlocal failures
        print(("ok  : " if ok else "FAIL: ") + what)
        failures += not ok

    check(lines == expected, f"converts notes and drums per beat ({lines})")
    check(report["time_signature"] == "3/4" and report["beats"] == 3, "reads the time signature and bar length")
    check(report["moved"] == 1, "counts the eighth note moved onto its beat")
    check(report["unknown_drums"] == {42: 1}, "reports drums that aren't in DRUMS")
    check(note_name(60) == "C4" and note_name(70) == "Bb4" and note_name(61) == "C#4",
          "names notes the way the game reads them")
    check(to_score(*read_midi(midi), bars=2)[0] == expected + ["", "", ""], "--bars pads with empty beats")
    data, _ = to_json(*read_midi(midi), source="test.mid")
    beat1 = data["score"][1]
    e4 = [n for n in beat1 if n.get("note") == "E4"]
    check(data["beats"] == 3 and data["time_signature"] == "3/4", "JSON: length and time signature")
    check(e4 == [{"note": "E4", "at": 0.5, "length": 0.5, "velocity": round(100 / 127, 3)}],
          f"JSON: an eighth keeps its place, length and velocity ({e4})")
    check({"note": "D2", "instrument": "DrumSynth", "at": 0.0, "velocity": round(90 / 127, 3)} in beat1,
          "JSON: drums are notes on the DrumSynth")
    check(json.loads(dump_json(data)) == data, "JSON: the written file reads back the same")
    def own_instruments(data):
        return {n.get("instrument") for b in data["score"] for n in b}
    check(data["instrument"] == DEFAULT_INSTRUMENT and own_instruments(data) == {None, "DrumSynth"},
          "JSON: one instrument is the score's, not repeated per note (drums name theirs)")
    data, _ = to_json(*read_midi(midi), default="PianoSynth")
    check(data["instrument"] == "PianoSynth", "JSON: --instrument NAME sets every channel's")
    # The notes are on channel 1, the drums on 10.
    data, _ = to_json(*read_midi(midi), instruments={1: "GuitarSynth"})
    check(data["instrument"] == "GuitarSynth" and own_instruments(data) == {None, "DrumSynth"},
          "JSON: --instrument CH=NAME sets that channel's")
    check(parse_instruments(["PianoSynth", "2=GuitarSynth"]) == ("PianoSynth", {2: "GuitarSynth"}),
          "reads --instrument options")
    # Two quarter notes a tick: 3/4's three beats are a tick and a half, so
    # the bar ends at tick 2 (rounded up to whole bars: 3 ticks for 2 bars).
    data, report = to_json(*read_midi(midi), beats_per_tick=2)
    e4 = [n for n in data["score"][0] if n.get("note") == "E4"]
    check(data["beats_per_tick"] == 2 and data["beats"] == 3 and report["bars"] == 2,
          f"--beats-per-tick: a tick holds two quarters ({data['beats']} ticks)")
    check(e4 == [{"note": "E4", "at": 0.75, "length": 0.25, "velocity": round(100 / 127, 3)}],
          f"--beats-per-tick: places and lengths are in ticks ({e4})")
    check(to_score(*read_midi(midi), beats_per_tick=2)[0] == ["Kick Snare C2 C4 E4", "Bb4", ""],
          "--beats-per-tick: the text format has a line a tick")
    try:
        read_midi(b"not a midi file at all")
        check(False, "refuses what isn't MIDI")
    except MidiError:
        check(True, "refuses what isn't MIDI")
    return failures == 0


def parse_instruments(options):
    """--instrument values: NAME for every channel, CH=NAME for one. Gives
    (the NAME given, or None, and {channel: instrument})."""
    default, channels = None, {}
    for option in options or []:
        channel, sep, name = option.partition("=")
        if not sep:
            default = option
            continue
        if not channel.isdigit() or not 1 <= int(channel) <= 16 or not name:
            raise ValueError(f"--instrument {option}: give NAME or CHANNEL=NAME, channel 1 to 16")
        channels[int(channel)] = name
    return default, channels


def main():
    parser = argparse.ArgumentParser(
        description="Turn a MIDI file into the game's text score, one quarter note per line.")
    parser.add_argument("midi", nargs="?", help="the .mid file")
    parser.add_argument("-o", "--output",
                        help="where to write the score (default: Assets/music/<name>.json); "
                             "a .txt name writes the text format")
    parser.add_argument("--text", action="store_true",
                        help="the text format: one line of names per beat, notes moved onto beats")
    parser.add_argument("--print", action="store_true", help="print the score instead of writing it")
    parser.add_argument("--bars", type=int, help="make the score exactly this many bars long")
    parser.add_argument("--instrument", action="append", metavar="[CH=]NAME",
                        help="the instrument notes play on: NAME for every channel, CH=NAME "
                             "for MIDI channel CH (1-16); repeatable (JSON only)")
    parser.add_argument("--beats-per-tick", type=int, default=1, metavar="N",
                        help="quarter notes per game tick (default 1: 60 BPM at normal speed; "
                             "2: 120 BPM)")
    parser.add_argument("--selftest", action="store_true", help="check the tool on a built-in file")
    args = parser.parse_args()
    if args.beats_per_tick < 1:
        parser.error("--beats-per-tick must be 1 or more")

    if args.selftest:
        return 0 if selftest() else 1
    if not args.midi:
        parser.error("give a .mid file (or --selftest)")

    as_text = args.text or (args.output or "").endswith(".txt")
    try:
        default, instruments = parse_instruments(args.instrument)
    except ValueError as error:
        parser.error(str(error))
    try:
        with open(args.midi, "rb") as f:
            midi = read_midi(f.read())
    except (OSError, MidiError) as error:
        print(f"{args.midi}: {error}", file=sys.stderr)
        return 1
    if as_text:
        lines, report = to_score(*midi, bars=args.bars, beats_per_tick=args.beats_per_tick)
        text = "\n".join(lines) + "\n"
    else:
        data, report = to_json(*midi, bars=args.bars, source=os.path.basename(args.midi),
                               instruments=instruments, default=default,
                               beats_per_tick=args.beats_per_tick)
        text = dump_json(data)

    if args.print:
        sys.stdout.write(text)
    else:
        output = args.output or os.path.join(
            "Assets", "music",
            os.path.splitext(os.path.basename(args.midi))[0] + (".txt" if as_text else ".json"))
        with open(output, "w", newline="\n") as f:
            f.write(text)
        print(f"wrote {args.output or os.path.relpath(output)}", file=sys.stderr)
    print_report(report)
    return 0


if __name__ == "__main__":
    sys.exit(main())
