#!/usr/bin/env python3
"""Turn a MIDI file into a score for timeless's music (timeless/music.hpp).

A score plays one quarter note per game tick, so the tempo is the game's: a
beat a tick (60 BPM at normal speed), faster when the game runs faster,
backwards when it rewinds. --beats-per-tick N packs N quarter notes into a
tick instead (N=2: 120 BPM), for music written at a faster tempo; the score
then says so ("beats_per_tick"), and score_to_midi.py writes it back out
that way.
parse_score() reads two formats:

- JSON (the default): one list of notes per beat, each with where in the beat
  it starts ("at", 0 to 1), its length in beats, and its velocity (0 to 1).
  Notes between beats are played there, delayed inside the tick.
- text (a .txt output, or --text): one line of names per beat, the older
  hand-written format. A note starting between
  beats is moved onto the beat before it; length and velocity are lost.

Run it from the game's root, like timeless/web/build-wasm.sh:

    timeless/tools/midi_to_score.py song.mid             # writes Assets/music/song.json
    timeless/tools/midi_to_score.py song.mid -o Assets/music/song.txt
    timeless/tools/midi_to_score.py song.mid --print     # to stdout, nothing written
    timeless/tools/midi_to_score.py song.mid --beats-per-tick 2   # two quarter notes a tick

Drums are MIDI channel 10, by General MIDI number: the drums in DRUMS below
are kept, others skipped. In JSON they are notes on the DrumSynth, which
plays those numbers (C2 kick, D2 snare, F#2/G#2 closed and A#2 open hi-hat);
in the text format they become the
sound events DRUMS names. Other channels are notes. Which instrument plays them (a name
SoundSystem::play_synth() knows, like "StringSynth" or "PianoSynth") is set
per channel in INSTRUMENTS below, or with --instrument:

    timeless/tools/midi_to_score.py song.mid --instrument PianoSynth     # every channel
    timeless/tools/midi_to_score.py song.mid --instrument 2=PianoSynth   # channel 2 only

In the JSON the score's most used instrument is the score's "instrument", and
only notes on another one carry their own. Tempo is ignored. The score runs to the end
of the last bar (from the file's time signature, 4/4 if it has none), so the
game loops it in time (loop_score()). A game that packs its assets only
hears a new score after a repack.

GENERATED BY CLAUDE CODE
"""

import argparse
import json
import math
import os
import sys

# Drum notes (General MIDI, channel 10): the ones the DrumSynth plays (JSON),
# and the sound event each one is in the text format (a name the game has
# samples for).
DRUMS = {
    35: "Kick",   # acoustic bass drum
    36: "Kick",   # bass drum
    38: "Snare",  # acoustic snare
    40: "Snare",  # electric snare
    # Only the DrumSynth plays these: the text format has no hi-hat sound
    # event, so they are silent there.
    42: "HiHat",      # closed hi-hat
    44: "HiHat",      # pedal hi-hat
    46: "OpenHiHat",  # open hi-hat
}
DRUM_CHANNEL = 9  # channel 10, counted from 0
DRUM_INSTRUMENT = "DrumSynth"

# The instrument each MIDI channel plays on (counted from 1, as DAWs show
# them). Channels not listed play on DEFAULT_INSTRUMENT. --instrument
# overrides both. score_to_midi.py writes each instrument on its channel
# here, so a score sent to MuseScore (or a DAW) and back keeps them.
INSTRUMENTS = {
    1: "StringSynth",
    2: "GuitarSynth",
    3: "BassSynth",
    4: "CelloSynth",
    5: "PianoSynth",
}
DEFAULT_INSTRUMENT = "StringSynth"

# Spelled as the current score spells them; tokkel::note_frequency() reads
# "C#" and "Db" alike.
NOTE_NAMES = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "G#", "A", "Bb", "B"]


class MidiError(Exception):
    pass


def note_name(note):
    """"C4" for MIDI note 60. None outside C0..B9, the octaves the game reads."""
    octave = note // 12 - 1
    if not 0 <= octave <= 9:
        return None
    return f"{NOTE_NAMES[note % 12]}{octave}"


def read_midi(data):
    """Parse a Standard MIDI File.

    Returns (ticks_per_quarter, notes, end, time_signature): notes are
    (start, length, channel, note, velocity), times in ticks, velocity 1-127;
    `end` is the latest end of track or note end, `time_signature` is
    (numerator, denominator) or None.
    """
    pos = 0

    def take(count):
        nonlocal pos
        if pos + count > len(data):
            raise MidiError("the file ends in the middle of a chunk")
        chunk = data[pos:pos + count]
        pos += count
        return chunk

    if take(4) != b"MThd":
        raise MidiError("not a MIDI file (no MThd header)")
    header_length = int.from_bytes(take(4), "big")
    header = take(header_length)
    if header_length < 6:
        raise MidiError("the MIDI header is too short")
    midi_format = int.from_bytes(header[0:2], "big")
    division = int.from_bytes(header[4:6], "big")
    if midi_format not in (0, 1):
        raise MidiError(f"MIDI format {midi_format}: only formats 0 and 1 are supported")
    if division & 0x8000:
        raise MidiError("the file uses SMPTE timing; export it with ticks per quarter note")
    if division == 0:
        raise MidiError("the file has 0 ticks per quarter note")

    notes = []
    end = 0
    time_signature = None

    while pos < len(data):
        if len(data) - pos < 8:
            break  # trailing padding some exporters leave
        kind = take(4)
        length = int.from_bytes(take(4), "big")
        track = take(length)
        if kind != b"MTrk":
            continue  # unknown chunks are allowed and skipped

        t_pos = 0
        time = 0
        status = None
        sounding = {}  # (channel, note) -> (start ticks, velocity), oldest first

        def byte():
            nonlocal t_pos
            if t_pos >= len(track):
                raise MidiError("a track ends in the middle of an event")
            value = track[t_pos]
            t_pos += 1
            return value

        def varlen():
            value = 0
            for _ in range(4):
                b = byte()
                value = (value << 7) | (b & 0x7F)
                if not b & 0x80:
                    return value
            raise MidiError("a variable-length number is longer than 4 bytes")

        def note_off(channel, note):
            starts = sounding.get((channel, note))
            if starts:
                start, velocity = starts.pop(0)
                notes.append((start, time - start, channel, note, velocity))

        while t_pos < len(track):
            time += varlen()
            first = byte()
            if first == 0xFF:  # meta event
                meta = byte()
                length = varlen()
                body = track[t_pos:t_pos + length]
                t_pos += length
                if meta == 0x58 and len(body) >= 2 and time_signature is None:
                    time_signature = (body[0], 2 ** body[1])
                elif meta == 0x2F:  # end of track
                    end = max(end, time)
                    break
                continue
            if first in (0xF0, 0xF7):  # sysex
                t_pos += varlen()
                status = None
                continue
            if first & 0x80:
                status = first
                data1 = byte()
            elif status is None:
                raise MidiError("a data byte without a status byte before it")
            else:
                data1 = first  # running status: the status of the last event
            kind_bits = status & 0xF0
            channel = status & 0x0F
            if kind_bits in (0xC0, 0xD0):  # program change, channel pressure
                continue
            data2 = byte()
            if kind_bits == 0x90 and data2 > 0:
                sounding.setdefault((channel, data1), []).append((time, data2))
            elif kind_bits == 0x80 or kind_bits == 0x90:  # note-on at velocity 0 is an off
                note_off(channel, data1)

        # Notes still sounding at the end of the track end there.
        for (channel, note), starts in sounding.items():
            for start, velocity in starts:
                notes.append((start, time - start, channel, note, velocity))
        end = max(end, time)

    for start, length, *_ in notes:
        end = max(end, start + length)
    return division, notes, end, time_signature


def to_score(division, notes, end, time_signature, bars=None, beats_per_tick=1):
    """The score's lines, and a report of what the quarter grid changed.

    A line is a tick: `beats_per_tick` quarter notes of the MIDI file."""
    numerator, denominator = time_signature or (4, 4)
    division *= beats_per_tick
    beats_per_bar = numerator * 4 / denominator / beats_per_tick

    drums, pitched = {}, {}
    moved = 0
    unknown_drums = {}
    out_of_range = set()
    last_beat = -1
    for start, length, channel, note, _ in notes:
        beat = start // division
        if channel == DRUM_CHANNEL:
            name = DRUMS.get(note)
            if name is None:
                unknown_drums[note] = unknown_drums.get(note, 0) + 1
                continue
            drums.setdefault(beat, set()).add(name)
        else:
            if note_name(note) is None:
                out_of_range.add(note)
                continue
            pitched.setdefault(beat, set()).add(note)
            # A note starting between beats is played on the beat before.
            if start % division:
                moved += 1
        last_beat = max(last_beat, beat)

    # Up to the end of the last bar; a few ticks past a bar line (a 16th) is
    # an exporter's rounding, not a new bar.
    quarters = max(end / division - 0.25, last_beat + 1, 1)
    if bars is not None:
        beats = math.ceil(bars * beats_per_bar)
    else:
        beats = math.ceil(math.ceil(quarters / beats_per_bar) * beats_per_bar)

    drum_order = list(dict.fromkeys(DRUMS.values()))
    lines = []
    for beat in range(beats):
        names = [d for d in drum_order if d in drums.get(beat, ())]
        names += [note_name(n) for n in sorted(pitched.get(beat, ()))]
        lines.append(" ".join(names))

    report = {
        "beats": beats,
        "bars": beats / beats_per_bar,
        "time_signature": f"{numerator}/{denominator}" + ("" if time_signature else " (none in the file)"),
        "moved": moved,
        "unknown_drums": unknown_drums,
        "out_of_range": sorted(out_of_range),
        "cut_off": max(0, last_beat + 1 - beats),
    }
    return lines, report


def to_json(division, notes, end, time_signature, bars=None, source="", instruments=None,
            default=None, beats_per_tick=1):
    """The score as a JSON-ready dict, and a report like to_score()'s.

    `instruments` maps channels (from 1) to instruments. Without a `default`,
    they go over INSTRUMENTS, and other channels play on DEFAULT_INSTRUMENT;
    with one (--instrument NAME), it replaces the table: every channel not in
    `instruments` plays on it."""
    if default is None:
        channel_instruments = {**INSTRUMENTS, **(instruments or {})}
        default = DEFAULT_INSTRUMENT
    else:
        channel_instruments = dict(instruments or {})
    # The length and the warnings are the text score's; only the notes differ.
    lines, report = to_score(division, notes, end, time_signature, bars, beats_per_tick)
    division *= beats_per_tick
    beats = report["beats"]
    report["moved"] = 0  # nothing is moved: notes keep their place in the beat
    score = [[] for _ in range(beats)]
    for start, length, channel, note, velocity in sorted(notes):
        beat = start // division
        if beat >= beats:
            continue
        entry = {}
        if channel == DRUM_CHANNEL:
            if note not in DRUMS:
                continue
            entry["note"] = note_name(note)
            entry["instrument"] = channel_instruments.get(DRUM_CHANNEL + 1, DRUM_INSTRUMENT)
        else:
            if note_name(note) is None:
                continue
            entry["note"] = note_name(note)
            entry["instrument"] = channel_instruments.get(channel + 1, default)
        entry["at"] = round((start % division) / division, 4)
        if channel != DRUM_CHANNEL:
            entry["length"] = round(length / division, 4)
        entry["velocity"] = round(velocity / 127, 3)
        score[beat].append(entry)
    # The most used instrument becomes the score's, so most notes don't have
    # to name it.
    counts = {}
    for beat in score:
        for entry in beat:
            if "instrument" in entry:
                counts[entry["instrument"]] = counts.get(entry["instrument"], 0) + 1
    instrument = max(sorted(counts), key=counts.get) if counts else default
    for beat in score:
        for entry in beat:
            if entry.get("instrument") == instrument:
                del entry["instrument"]
    report["instruments"] = counts
    numerator, denominator = time_signature or (4, 4)
    data = {
        "source": source,
        "time_signature": f"{numerator}/{denominator}",
    }
    if beats_per_tick != 1:
        data["beats_per_tick"] = beats_per_tick
    data.update({"beats": beats, "instrument": instrument, "score": score})
    return data, report


def dump_json(data):
    """JSON with one beat per line, so a score can still be read and diffed."""
    head = {key: value for key, value in data.items() if key != "score"}
    lines = ["{"]
    for key, value in head.items():
        lines.append(f"  {json.dumps(key)}: {json.dumps(value)},")
    lines.append('  "score": [')
    beats = data["score"]
    for i, beat in enumerate(beats):
        comma = "," if i + 1 < len(beats) else ""
        lines.append("    " + json.dumps(beat, separators=(", ", ": ")) + comma)
    lines.append("  ]")
    lines.append("}")
    return "\n".join(lines) + "\n"


def print_report(report, out=sys.stderr):
    print(f"{report['beats']} beats, {report['bars']:g} bars of "
          f"{report['time_signature']}", file=out)
    if report["moved"]:
        print(f"{report['moved']} notes started between beats and were moved onto "
              f"the beat before", file=out)
    for note, count in sorted(report["unknown_drums"].items()):
        print(f"drum note {note} ({count}x) skipped: not in DRUMS", file=out)
    if report["out_of_range"]:
        print(f"notes {report['out_of_range']} skipped: outside C0..B9", file=out)
    for instrument, count in sorted(report.get("instruments", {}).items()):
        print(f"{count} notes on {instrument}", file=out)
    if report["cut_off"]:
        print(f"{report['cut_off']} beats with notes cut off by --bars", file=out)


